"""Markdown calibration report generation."""
from .agreement import mean_of
from .dataset import CATEGORIES, CRITERIA
from .drift import first_level_below, rank_by_drop

DISCLOSURE = ("> **SYNTHETIC DATA.** All traces and 'expert' labels in this report are generated by a "
              "seeded script. The experts are random processes, not people. Kappa values demonstrate "
              "the pipeline, not a production calibration claim.")


def _f(x):
    return "%.2f" % x


def render_markdown(r):
    L = []
    h = r["headline"]
    nlab = len(r["labels"])
    L.append("# Eval Calibration Report (sample)")
    L.append("")
    L.append(DISCLOSURE)
    L.append("")
    L.append("Seed: %s | Traces: %d | Traces with labels: %d" % (r["seed"], len(r["traces"]), nlab))
    L.append("")
    L.append("## Headline agreement")
    L.append("")
    L.append("| Pair | Mean % agreement | Mean Cohen's kappa |")
    L.append("|---|---|---|")
    L.append("| Judge vs experts | %s | %s |" % (_f(100 * h["judge_agree_mean"]) + "%", _f(h["judge_kappa_mean"])))
    L.append("| Expert vs expert (baseline) | %s | %s |" % (_f(100 * h["expert_agree_mean"]) + "%", _f(h["expert_kappa_mean"])))
    L.append("")
    L.append("## Per-criterion agreement")
    L.append("")
    L.append("| Criterion | Judge-vs-expert % | Judge-vs-expert kappa | Expert-vs-expert % | Expert-vs-expert kappa |")
    L.append("|---|---|---|---|---|")
    for c in CRITERIA:
        j, e = r["judge_vs_expert"][c], r["expert_vs_expert"][c]
        L.append("| %s | %s | %s | %s | %s |" % (
            c, _f(100 * mean_of(j, "agreement")), _f(mean_of(j, "kappa")),
            _f(100 * mean_of(e, "agreement")), _f(mean_of(e, "kappa"))))
    L.append("")
    L.append("### Judge vs each expert (kappa / % agreement / n)")
    L.append("")
    experts = sorted({x for c in CRITERIA for x in r["judge_vs_expert"][c]})
    L.append("| Criterion | " + " | ".join(experts) + " |")
    L.append("|---|" + "---|" * len(experts))
    for c in CRITERIA:
        cells = []
        for x in experts:
            s = r["judge_vs_expert"][c].get(x)
            cells.append("%s / %s%% / %d" % (_f(s["kappa"]), _f(100 * s["agreement"]), s["n"]) if s else "-")
        L.append("| %s | %s |" % (c, " | ".join(cells)))
    L.append("")
    L.append("### Expert vs expert pairs (kappa / % agreement / n)")
    L.append("")
    pairs = sorted({p for c in CRITERIA for p in r["expert_vs_expert"][c]})
    L.append("| Criterion | " + " | ".join(pairs) + " |")
    L.append("|---|" + "---|" * len(pairs))
    for c in CRITERIA:
        cells = []
        for p in pairs:
            s = r["expert_vs_expert"][c].get(p)
            cells.append("%s / %s%% / %d" % (_f(s["kappa"]), _f(100 * s["agreement"]), s["n"]) if s else "-")
        L.append("| %s | %s |" % (c, " | ".join(cells)))
    L.append("")
    L.append("## Rules layer (deterministic) by category")
    L.append("")
    L.append("| Category | n | escalation ok | policy cited | no outside promise | all pass |")
    L.append("|---|---|---|---|---|---|")
    for cat in CATEGORIES:
        ts = [t["trace_id"] for t in r["traces"] if t["category"] == cat]
        rs = [r["rules"][t] for t in ts]
        L.append("| %s | %d | %d | %d | %d | %d |" % (
            cat, len(ts), sum(x["escalation_ok"] for x in rs), sum(x["policy_cited"] for x in rs),
            sum(x["no_promise_outside_tools"] for x in rs), sum(x["passed"] for x in rs)))
    L.append("")
    L.append("## Divergence report (judge vs experts)")
    L.append("")
    ranked = sorted(CRITERIA, key=lambda c: (-r["divergence"][c]["disagreement_rate"], c))
    L.append("| Criterion | Disagreement rate | Mean abs diff |")
    L.append("|---|---|---|")
    for c in ranked:
        d = r["divergence"][c]
        L.append("| %s | %s%% | %s |" % (c, _f(100 * d["disagreement_rate"]), _f(d["mean_abs_diff"])))
    L.append("")
    for c in ranked[:3]:
        exs = r["divergence"][c]["examples"]
        L.append("**%s - largest gaps**" % c)
        L.append("")
        if not exs:
            L.append("_No divergent examples._")
        for ex in exs:
            L.append("- %s (%s): judge=%d, experts=%s. Response: \"%s\"" % (
                ex["trace_id"], ex["category"], ex["judge"],
                ", ".join("%s=%d" % kv for kv in sorted(ex["experts"].items())), ex["response"]))
        L.append("")
    L.append("## Drift report")
    L.append("")
    lv = r["drift"]["levels"]
    for key, title in (("label_noise", "Label noise injected into one criterion at a time"),
                       ("judge_degradation", "Judge degraded on one criterion at a time")):
        series = r["drift"][key]
        L.append("### " + title)
        L.append("")
        L.append("Mean judge-vs-expert kappa for the degraded criterion at each corruption rate.")
        L.append("")
        L.append("| Criterion | " + " | ".join("p=%s" % _f(p) for p in lv) + " | first p with kappa < 80% of baseline |")
        L.append("|---|" + "---|" * (len(lv) + 1))
        for c in CRITERIA:
            fl = first_level_below(series[c], lv)
            L.append("| %s | %s | %s |" % (c, " | ".join(_f(k) for k in series[c]),
                                           _f(fl) if fl is not None else "never"))
        L.append("")
        order = rank_by_drop(series)
        L.append("Ranked by kappa drop (largest first): " +
                 ", ".join("%s (%s)" % (c, _f(d)) for c, d in order))
        L.append("")
    L.append("## Caveats")
    L.append("")
    L.append("- Labels are synthetic; subjective disagreement is planted by construction.")
    L.append("- Small n per pair; kappa is unstable and unweighted (ordinal scale treated as categorical).")
    L.append("- The judge is a deterministic heuristic, not an LLM.")
    L.append("")
    return "\n".join(L)
